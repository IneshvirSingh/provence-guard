"""``make report``: docs/RESULTS.md generated from results/*.json. Numbers exist only if a file does."""

from __future__ import annotations

from pathlib import Path

from provguard.bench.runner import ArmResult

HEADER = """# Results

Generated by `make report` from `results/*.json`. Every number traces to a file; missing arms are `[PENDING]`.
`security=True` in AgentDojo means the injection goal was achieved, so targeted ASR = mean(security).
Intervals are Wilson 95% CIs.
"""


def load_results(results_dir: Path) -> list[ArmResult]:
    return [ArmResult.model_validate_json(p.read_text()) for p in sorted(results_dir.glob("*.json"))]


def _guarded(a: ArmResult) -> str:
    if not a.guard:
        return "-"
    g = a.guard
    reached, total = g.get("requests_reaching_guarded_call", 0), g.get("requests", 0)
    return f"{reached}/{total} (CONFIRM {g.get('requests_with_confirmation', 0)})"


def render(arms: list[ArmResult]) -> str:
    lines = [
        HEADER,
        "| suite | scope | defense | attack | model | benign utility | utility under attack | targeted ASR "
        "| requests | tokens live (+ served from cache) | reached guarded call | git |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    if not arms:
        lines.append(
            "| banking | full | none | important_instructions | [PENDING] | [PENDING] | [PENDING] "
            "| [PENDING] "
            "| - | - | - | - |"
        )
    for a in arms:
        m, u = a.metrics, a.usage
        lines.append(
            f"| {a.spec.suite} | {a.spec.label or 'full'} | {a.spec.defense} | {a.spec.attack or 'none'} "
            f"| {a.spec.model} "
            f"| {m.benign_utility.fmt()} | {m.utility_under_attack.fmt()} | {m.targeted_asr.fmt()} "
            f"| {u.get('requests', 0)} (+{u.get('cache_hits', 0)} cached) "
            f"| {u.get('total_tokens', 0)} (+{u.get('cached_total_tokens', 0)}) | {_guarded(a)} "
            f"| {str(a.meta.get('git_sha', ''))[:7]} |"
        )
    return "\n".join(lines) + "\n"


def write_report(results_dir: Path = Path("results"), out: Path = Path("docs/RESULTS.md")) -> Path:
    out.write_text(render(load_results(results_dir)))
    return out
